
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st

# -------------------- PATHS --------------------

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "models" / "placement_model.pkl"
PLACEMENT_DATA_PATH = BASE_DIR / "data" / "placement_dataset.csv"
JOB_DATA_PATH = BASE_DIR / "data" / "job_roles.csv"


# -------------------- PAGE CONFIGURATION --------------------

st.set_page_config(
    page_title="PlacementAI",
    page_icon="🎓",
    layout="wide"
)

st.title("🎓 PlacementAI")
st.subheader("Student Placement Prediction and Job Recommendation System")

st.write(
    "Enter your academic details to estimate your placement status, "
    "explore suitable IT job roles, and identify skills to improve."
)

st.info(
    "The placement result is an estimate generated by a machine-learning "
    "model. It does not guarantee actual placement."
)


# -------------------- LOAD FILES --------------------

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)


@st.cache_data
def load_datasets():
    placement_df = pd.read_csv(PLACEMENT_DATA_PATH)
    jobs_df = pd.read_csv(JOB_DATA_PATH)

    return placement_df, jobs_df


try:
    model_bundle = load_model()
    model = model_bundle["model"]
    placement_df, jobs_df = load_datasets()

except FileNotFoundError as error:
    st.error(f"Required file not found: {error}")
    st.info(
        "Check that the model is inside the models folder and both CSV "
        "files are inside the data folder."
    )
    st.stop()

except Exception as error:
    st.error(f"Unable to load the project files: {error}")
    st.stop()


# -------------------- PREPARE JOB DATA --------------------

jobs_df.columns = jobs_df.columns.str.strip()

required_job_columns = [
    "Job Title",
    "Job Description",
    "Skills",
    "Certifications"
]

missing_columns = [
    column for column in required_job_columns
    if column not in jobs_df.columns
]

if missing_columns:
    st.error(f"Missing columns in job_roles.csv: {missing_columns}")
    st.stop()

jobs_df["Job Title"] = jobs_df["Job Title"].fillna("Unknown Job Role")
jobs_df["Job Description"] = jobs_df["Job Description"].fillna(
    "No description available."
)
jobs_df["Skills"] = jobs_df["Skills"].fillna("")
jobs_df["Certifications"] = jobs_df["Certifications"].fillna("")

job_titles = sorted(
    jobs_df["Job Title"].dropna().astype(str).unique().tolist()
)


# -------------------- NAVIGATION --------------------

tab_prediction, tab_recommendation, tab_about = st.tabs(
    ["📊 Placement Prediction", "💼 Job Recommendations", "ℹ️ About"]
)


# -------------------- PLACEMENT PREDICTION --------------------

with tab_prediction:
    st.header("Enter Your Details")

    with st.form("placement_form"):
        col1, col2 = st.columns(2)

        with col1:
            cgpa = st.number_input(
                "CGPA",
                min_value=0.0,
                max_value=10.0,
                value=7.5,
                step=0.1
            )

            internships = st.number_input(
                "Number of Internships",
                min_value=0,
                max_value=20,
                value=1,
                step=1
            )

            projects = st.number_input(
                "Number of Projects",
                min_value=0,
                max_value=50,
                value=2,
                step=1
            )

            workshops = st.number_input(
                "Workshops / Certifications",
                min_value=0,
                max_value=50,
                value=2,
                step=1
            )

            aptitude = st.slider(
                "Aptitude Test Score",
                min_value=0,
                max_value=100,
                value=70
            )

        with col2:
            soft_skills = st.slider(
                "Soft Skills Rating",
                min_value=0.0,
                max_value=5.0,
                value=3.5,
                step=0.5
            )

            extracurricular = st.selectbox(
                "Extracurricular Activities",
                ["Yes", "No"]
            )

            training = st.selectbox(
                "Placement Training",
                ["Yes", "No"]
            )

            ssc_marks = st.slider(
                "SSC Marks (%)",
                min_value=0,
                max_value=100,
                value=80
            )

            hsc_marks = st.slider(
                "HSC Marks (%)",
                min_value=0,
                max_value=100,
                value=80
            )

        submitted = st.form_submit_button(
            "Predict Placement Status",
            type="primary",
            use_container_width=True
        )

    if submitted:
        student_data = pd.DataFrame([{
            "CGPA": cgpa,
            "Internships": internships,
            "Projects": projects,
            "Workshops/Certifications": workshops,
            "AptitudeTestScore": aptitude,
            "SoftSkillsRating": soft_skills,
            "ExtracurricularActivities": extracurricular,
            "PlacementTraining": training,
            "SSC_Marks": ssc_marks,
            "HSC_Marks": hsc_marks
        }])

        try:
            prediction = model.predict(student_data)[0]

            st.divider()
            st.subheader("Your Prediction")

            if str(prediction).strip().lower() == "placed":
                st.success("The model estimates that you may be placed.")
            else:
                st.warning(
                    "The model estimates that you may need further "
                    "preparation to improve your placement chances."
                )

            if hasattr(model, "predict_proba"):
                probabilities = model.predict_proba(student_data)[0]
                classes = list(model.classes_)

                if prediction in classes:
                    index = classes.index(prediction)
                    confidence = float(probabilities[index]) * 100

                    st.metric(
                        "Model confidence for this predicted class",
                        f"{confidence:.2f}%"
                    )

                    st.caption(
                        "This is the model's estimated probability for "
                        "its predicted class, not a guarantee of your "
                        "real-world placement chances."
                    )

        except Exception as error:
            st.error(f"Prediction failed: {error}")


# -------------------- JOB RECOMMENDATIONS --------------------

with tab_recommendation:
    st.header("Explore IT Job Roles")

    st.write(
        "Choose a job role to view its description, required skills, "
        "and certifications."
    )

    if not job_titles:
        st.warning("No job titles were found in job_roles.csv.")

    else:
        selected_job = st.selectbox(
            "Select a Job Role",
            job_titles
        )

        selected_rows = jobs_df[
            jobs_df["Job Title"].astype(str) == selected_job
        ]

        if not selected_rows.empty:
            job = selected_rows.iloc[0]

            st.subheader(str(job["Job Title"]))
            st.write(str(job["Job Description"]))

            required_skills = [
                skill.strip()
                for skill in str(job["Skills"]).split(",")
                if skill.strip()
            ]

            required_certifications = [
                cert.strip()
                for cert in str(job["Certifications"]).split(",")
                if cert.strip()
            ]

            st.markdown("**Skills listed for this role**")

            if required_skills:
                st.write(", ".join(required_skills))
            else:
                st.write("No skill information is available for this role.")

            st.markdown("**Suggested certifications**")

            if required_certifications:
                st.write(", ".join(required_certifications))
            else:
                st.write("No certification information is available.")

            st.divider()
            st.subheader("Skill Gap Analysis")

            st.write(
                "Enter the technical skills you already know. "
                "Separate them with commas."
            )

            student_skills_text = st.text_input(
                "Your current skills",
                placeholder="Example: Python, SQL, HTML"
            )

            if st.button("Analyze My Skill Gap"):
                student_skills = {
                    skill.strip().casefold()
                    for skill in student_skills_text.split(",")
                    if skill.strip()
                }

                required_skill_set = {
                    skill.casefold(): skill
                    for skill in required_skills
                }

                matched_skills = [
                    original_skill
                    for normalized, original_skill
                    in required_skill_set.items()
                    if normalized in student_skills
                ]

                missing_skills = [
                    original_skill
                    for normalized, original_skill
                    in required_skill_set.items()
                    if normalized not in student_skills
                ]

                left, right = st.columns(2)

                with left:
                    st.markdown("**Skills you already have**")
                    if matched_skills:
                        for skill in matched_skills:
                            st.write(f"✅ {skill}")
                    else:
                        st.write("No exact skill matches found.")

                with right:
                    st.markdown("**Skills to consider learning**")
                    if missing_skills:
                        for skill in missing_skills:
                            st.write(f"📘 {skill}")
                    else:
                        st.success(
                            "You listed all the skills available "
                            "for this role in the dataset."
                        )

                st.caption(
                    "Recommendations are based on the selected role's "
                    "dataset entry and exact skill-name matching."
                )


# -------------------- ABOUT --------------------

